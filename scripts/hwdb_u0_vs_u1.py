#!/usr/bin/env python3
"""hwdb_u0_vs_u1 — registers that read differently on unit 0 (a1, awto-uboot state) and unit 1 (a2, cold) (#86).

Usage: hwdb_u0_vs_u1.py     reads hwdb/validation/u{0,1}-values.tsv, writes hwdb/validation/u0-vs-u1.tsv + prints the counts per cause.
Only registers read on both units. cause = first matching class (CAUSES); `boot-config` = the rest (set by uboot-1/awto-uboot/Linux on unit 0, never initialised on unit 1).
"""
import csv
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
V = ROOT / "hwdb/validation"
CAUSES = [
    ("uninit-ram", r"^CMIC_LEDUP\d_(DATA|PROGRAM)_RAM|^CMIC_SCHAN_RCPU_RPIO_MESSAGE|^CMIC_CMC\d_SCHAN_MESSAGE", "RAM that powers up with chip-specific noise (not 0): differs per chip"),
    ("ddr", r"^DDR_", "unit 0 DDR controller/PHY hold the trained config of the live DRAM, unit 1 DDR is inert (reads 0, #92)"),
    ("nand", r"^NAND_", "NAND controller: both units differ from regdb (#93); values differ per chip"),
    ("arm-ip", r"^IHOST_", "A9 debug/PMU/GIC/L2/timer live values: a1 runs Linux or awto-uboot, a2 idles"),
    ("idm-errlog", r"IDM_ERROR_LOG|IDM_INTERRUPT_STATUS", "IDM error-log enable (unit 0 = 0x33a, unit 1 = reset 0x40) and captured faults: set on unit 0 before awto-uboot (boot ROM or uboot-1, not determined)"),
    ("chip-id", r"^(CMIC_DEV_REV_ID|PAXB_0_STRAP_STATUS|DMU_PCU_IPROC_STRAPS_CAPTURED|IPROC_WRAP_IPROC_XGPLL_STATUS|AMAC_IDM0_IO_STATUS|CMIC_GP_)", "chip revision / strap capture / board wiring: differs per unit"),
]
CAUSE_TEXT = {c: t for c, _, t in CAUSES} | {"boot-config": "RW or status registers programmed by uboot-1/awto-uboot/Linux on unit 0 (clock policy, PAXB RC windows, QSPI/MSPI, SBUS ring map, MIIM, ...); unit 1 is untouched or initialised by a2/us48_pci"}


def load(u):
    return {r["key"]: r for r in csv.DictReader(open(V / f"u{u}-values.tsv"), delimiter="\t")}


def main():
    u0, u1 = load(0), load(1)
    rows, cnt = [], Counter()
    for k, r in u0.items():
        a, b = r["uboot"], u1[k]["cold"]
        if "-" in (a, b) or a == b or a.startswith("A") or b.startswith("A"):
            continue
        name = k.split(".", 1)[1]
        cause = next((c for c, pat, _ in CAUSES if re.search(pat, name)), "boot-config")
        cnt[cause] += 1
        rows.append((k, r["addr"], r["rst"], a, r["linux"], b, u1[k]["warm"], cause))
    both = sum(1 for k, r in u0.items() if "-" not in (r["uboot"], u1[k]["cold"]) and not r["uboot"].startswith("A") and not u1[k]["cold"].startswith("A"))
    with open(V / "u0-vs-u1.tsv", "w") as f:
        f.write("# generated by scripts/hwdb_u0_vs_u1.py: registers read on both units whose value differs (u0 = awto-uboot state, u1 = cold), #86\n")
        f.write("key\taddr\trst\tu0_uboot\tu0_linux\tu1_cold\tu1_warm\tcause\n")
        for x in rows:
            f.write("\t".join(x) + "\n")
    print(f"read on both: {both}, differ: {len(rows)}")
    for c, n in cnt.most_common():
        print(f"{c}: {n}: {CAUSE_TEXT[c]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

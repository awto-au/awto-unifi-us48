#!/usr/bin/env python3
"""gen_bcm_hr2_init1_min — minimum unit-1 cold init list -> common/bcm-cmic/bcm_cmic_hr2_init1_min_data.h (#78).

Usage: scripts/gen_bcm_hr2_init1_min.py   (input: python3 scripts/init_phases.py --emit-min tmp/u1_min_init.txt)
- Input line: <ord> <ms> REG|MEM blk<N> <addr> <data words...> <name> <phase>  (rule-derived list, docs/init-phases-u1.md).
- Output entry: {cat<<24 | op<<16 | blk<<8 | words, addr, data...}, cat 2 (global); cat 0xff = hardware wait (ms).
- Waits: 9 ms (stock 10 ms - 10 %) after a TOP reset / XGXS power-up write that the stock trace followed by a gap >= 9 ms.
- Log: tmp/logs/gen_bcm_hr2_init1_min.log
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tmp/u1_min_init.txt"
OUT = ROOT / "common/bcm-cmic/bcm_cmic_hr2_init1_min_data.h"
LOG = ROOT / "tmp/logs/gen_bcm_hr2_init1_min.log"
HW_WAIT_MS = 9
HW_WAIT = {(16, 0x2030400), (16, 0x2030800), (16, 0x2031400), (5, 0x2021400)}
OPS = {"REG": 0x0d, "MEM": 0x09}


def main() -> int:
    if not SRC.exists():
        sys.exit(f"{SRC} missing: python3 scripts/init_phases.py --emit-min {SRC}")
    ops = []
    for ln in SRC.read_text().splitlines():
        t = ln.split()
        data = []
        for w in t[5:]:
            if not re.fullmatch(r"[0-9a-f]{8}", w):
                break
            data.append(int(w, 16))
        ops.append((int(t[1]), OPS[t[2]], int(t[3][3:]), int(t[4], 16), data))
    body, waits = [], 0
    for i, (ms, op, blk, addr, data) in enumerate(ops):
        if not 1 <= len(data) <= 20:
            sys.exit(f"ord line {i}: {len(data)} data words")
        body.append(f"0x{2 << 24 | op << 16 | blk << 8 | len(data):08x}, 0x{addr:08x}, " + ", ".join(f"0x{d:08x}" for d in data) + ",")
        if i + 1 < len(ops) and (blk, addr & ~0xff) in HW_WAIT and ops[i + 1][0] - ms >= HW_WAIT_MS:
            body.append(f"0xff000000 | {HW_WAIT_MS},")
            waits += 1
    OUT.write_text(f"/* Generated by scripts/gen_bcm_hr2_init1_min.py from tmp/u1_min_init.txt: {len(ops)} ops, {waits} waits. */\n" +
                   "\n".join(body) + "\n")
    LOG.parent.mkdir(parents=True, exist_ok=True)
    msg = f"{OUT.relative_to(ROOT)}: {len(ops)} ops, {waits} waits, {OUT.stat().st_size} bytes"
    LOG.write_text(msg + "\n")
    print(msg)
    return 0


if __name__ == "__main__":
    sys.exit(main())

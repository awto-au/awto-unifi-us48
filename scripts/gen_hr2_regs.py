#!/usr/bin/env python3
"""Generate hr2-regs.h (offsets + GENMASK fields) and hr2_regs.py (lookup module) from the HR2 DB TSVs.

Input: regdb/hr2_regs.tsv, hr2_mems.tsv, hr2_blocks.tsv (scripts/hr2_regdb.py).
Output: regdb/hr2-regs.h, regdb/hr2_regs.py. Generated, never hand-edited; committed (#43).
Log: tmp/logs/gen_hr2_regs.log.

Usage: python3 scripts/gen_hr2_regs.py [--dir regdb]
"""
import argparse
import csv
import logging
import os
import pathlib
import re
import subprocess
import sys


def repo_root():
    env = os.environ.get("US48_REPO")
    if env:
        return pathlib.Path(env)
    try:
        out = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True,
                             cwd=pathlib.Path(__file__).resolve().parent, check=True)
        return pathlib.Path(out.stdout.strip())
    except (subprocess.CalledProcessError, FileNotFoundError):
        return pathlib.Path(__file__).resolve().parent.parent


def ident(s):
    return re.sub(r"\W", "_", s).upper()


def parse_fields(spec):
    out = []
    for item in spec.split(",") if spec else []:
        name, bp, ln = item.rsplit(":", 2)
        out.append((name, int(bp), int(ln)))
    return out


def read(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


MODULE_TAIL = '''

REGTYPE_NAMES = {1: "gen", 2: "port", 4: "cos", 9: "cpureg", 13: "mcsreg", 14: "iprocreg"}
FLAG_NAMES = {0x1: "64BIT", 0x2: "COUNTER", 0x4: "ARRAY", 0x8: "NO_DGNL", 0x10: "RO", 0x20: "WO", 0x40: "ED_CNTR"}


def by_offset(offset, regtype=None):
    """All register names at an offset (optionally one regtype)."""
    return [n for n, r in REGS.items() if r[3] == offset and (regtype is None or r[1] == regtype)]


def decode(name, value):
    """Return [(field, bp, len, field value)] for REGS[name], sorted by bit position."""
    return [(f, bp, ln, (value >> bp) & ((1 << ln) - 1)) for f, bp, ln in sorted(REGS[name][6], key=lambda x: x[1])]


if __name__ == "__main__":
    import sys
    key = sys.argv[1]
    names = [key] if key in REGS else by_offset(int(key, 0))
    for n in names:
        r = REGS[n]
        print(f"{n} idx={r[0]:#x} regtype={REGTYPE_NAMES.get(r[1], r[1])} offset={r[3]:#x} numels={r[4]} flags={r[5]:#x}")
        if len(sys.argv) > 2:
            for f, bp, ln, v in decode(n, int(sys.argv[2], 0)):
                print(f"  [{bp + ln - 1}:{bp}] {f} = {v:#x}")
'''


def main():
    root = repo_root()
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dir", default=str(root / "regdb"))
    a = ap.parse_args()
    d = pathlib.Path(a.dir)
    log = root / "tmp/logs/gen_hr2_regs.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(message)s",
                        handlers=[logging.FileHandler(log, "w"), logging.StreamHandler(sys.stdout)])
    regs, mems, blocks = read(d / "hr2_regs.tsv"), read(d / "hr2_mems.tsv"), read(d / "hr2_blocks.tsv")

    seen = set()

    def define(out, macro, value, comment=""):
        if macro in seen:
            raise SystemExit(f"macro collision: {macro}")
        seen.add(macro)
        out.append(f"#define {macro} {value}" + (f"  /* {comment} */" if comment else ""))

    h = ["/* Generated by scripts/gen_hr2_regs.py from the stock HR2 SDK tables. Do not edit. */",
         "#ifndef HR2_REGS_H", "#define HR2_REGS_H", "", "#include <linux/bits.h>", ""]
    h.append("/* Block rows: SBUS/schan block numbers (type, number, schan) */")
    for b in blocks:
        define(h, f"HR2_BLK{b['row']}_SCHAN", b["schan"], f"{b['label']} #{b['number']} (type {b['type']})")
    h.append("")
    nfields = 0
    for r in regs:
        n = ident(r["name"])
        define(h, f"HR2_{n}_OFFS", r["offset"], f"{r['regtype_name']} {r['block_labels']} idx {int(r['idx']):#x}")
        if int(r["numels"]) > 1:
            define(h, f"HR2_{n}_NUMELS", r["numels"])
        for f, bp, ln in parse_fields(r["fields"]):
            hi = bp + ln - 1
            if hi < 32:
                define(h, f"HR2_{n}_{ident(f)}_MASK", f"GENMASK({hi}, {bp})")
            elif hi < 64:
                define(h, f"HR2_{n}_{ident(f)}_MASK", f"GENMASK_ULL({hi}, {bp})")
            else:
                define(h, f"HR2_{n}_{ident(f)}_BP", bp)
                define(h, f"HR2_{n}_{ident(f)}_LEN", ln)
            nfields += 1
    h.append("")
    for m in mems:
        n = ident(m["name"])
        define(h, f"HR2_MEM_{n}_BASE", m["base"], f"blocks {m['block_labels']} schan {m['schan']}")
        define(h, f"HR2_MEM_{n}_INDEX_MAX", m["index_max"])
        define(h, f"HR2_MEM_{n}_BYTES", m["bytes"])
        for f, bp, ln in parse_fields(m["fields"]):
            define(h, f"HR2_MEM_{n}_{ident(f)}_BP", bp)
            define(h, f"HR2_MEM_{n}_{ident(f)}_LEN", ln)
            nfields += 1
    h += ["", "#endif /* HR2_REGS_H */", ""]
    (d / "hr2-regs.h").write_text("\n".join(h))

    p = ["# Generated by scripts/gen_hr2_regs.py. Do not edit.",
         "# REGS[name] = (idx, regtype, blocks, offset, numels, flags, ((field, bp, len), ...))",
         "# MEMS[name] = (idx, base, index_min, index_max, bytes, flags, blk_rows, ((field, bp, len), ...))",
         "# BLOCKS = [(row, type, number, schan, label)]", "", "REGS = {"]
    for r in regs:
        p.append(f"    {r['name']!r}: ({int(r['idx'])}, {int(r['regtype'])}, "
                 f"{tuple(int(x) for x in r['blocks'].split(',') if x)!r}, {int(r['offset'], 16)}, {int(r['numels'])}, "
                 f"{int(r['flags'], 16)}, {tuple(parse_fields(r['fields']))!r}),")
    p += ["}", "", "MEMS = {"]
    for m in mems:
        p.append(f"    {m['name']!r}: ({int(m['idx'])}, {int(m['base'], 16)}, {int(m['index_min'])}, "
                 f"{int(m['index_max'])}, {int(m['bytes'])}, {int(m['flags'], 16)}, "
                 f"{tuple(int(x) for x in m['blk_rows'].split(',') if x)!r}, {tuple(parse_fields(m['fields']))!r}),")
    p += ["}", "", "BLOCKS = ["]
    for b in blocks:
        p.append(f"    ({b['row']}, {b['type']}, {b['number']}, {b['schan']}, {b['label']!r}),")
    p += ["]", MODULE_TAIL]
    (d / "hr2_regs.py").write_text("\n".join(p))
    logging.info("regs %d mems %d blocks %d fields %d macros %d", len(regs), len(mems), len(blocks), nfields, len(seen))
    logging.info("wrote %s and %s", d / "hr2-regs.h", d / "hr2_regs.py")


if __name__ == "__main__":
    main()

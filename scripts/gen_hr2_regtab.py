#!/usr/bin/env python3
"""gen_hr2_regtab — regdb/hr2_regs.tsv -> common/bcm-cmic/bcm_cmic_hr2_regtab.h (register list for `hr2reg`, #46).

Usage: scripts/gen_hr2_regtab.py
- One row per gen/port register on IPIPE (blk 10), EPIPE (11), MMU (12), TOP (16): name, block, offset, elements, words, port flag, counter flag.
- Port registers are read at CPU port 0 and front-1 logical port 2 (address = offset | port); array elements step 0x100.
- Log: tmp/logs/gen_hr2_regtab.log
"""
import csv
from pathlib import Path
from _cli import help_guard  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "regdb/hr2_regs.tsv"
OUT = ROOT / "common/bcm-cmic/bcm_cmic_hr2_regtab.h"
LOG = ROOT / "tmp/logs/gen_hr2_regtab.log"
BLKS = {"TOP": 16, "IPIPE": 10, "EPIPE": 11, "MMU": 12}


def words(r) -> int:
    bits = 0
    for f in filter(None, r["fields"].split(",")):
        _n, bp, ln = f.rsplit(":", 2)
        bits = max(bits, int(bp) + int(ln))
    if not bits:
        return 2 if int(r["rmask_hi"], 16) or int(r["rst_hi"], 16) else 1
    return min(4, (bits + 31) // 32)


def main() -> None:
    rows = []
    for r in csv.DictReader(SRC.open(), delimiter="\t"):
        lab = r["block_labels"].split(",")[0]
        if lab not in BLKS or r["regtype_name"] not in ("gen", "port"):
            continue
        rows.append((BLKS[lab], int(r["offset"], 16), r["name"], int(r["numels"]), words(r),
                     r["regtype_name"] == "port", r["ctr_idx"] != "0xffffffff"))
    rows.sort()
    out = ["/* Generated by scripts/gen_hr2_regtab.py from regdb/hr2_regs.tsv. Do not edit. */",
           "/* { name, S-channel block, offset, elements, words, port reg (read at ports 0 and 2), counter } */"]
    out += [f'\t{{ "{n}", {b}, 0x{o:08x}, {ne}, {w}, {int(p)}, {int(c)} }},' for b, o, n, ne, w, p, c in rows]
    OUT.write_text("\n".join(out) + "\n")
    inst = sum(r[3] * (2 if r[5] else 1) for r in rows)
    LOG.parent.mkdir(parents=True, exist_ok=True)
    LOG.write_text(f"{len(rows)} registers, {inst} instances -> {OUT}\n")
    print(LOG.read_text(), end="")


if __name__ == "__main__":
    help_guard(__doc__)
    main()

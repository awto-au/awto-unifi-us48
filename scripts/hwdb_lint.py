#!/usr/bin/env python3
"""List hard-coded MMIO literals (0x18/19/1b/1c/48 xxxxxx) that match an hwdb entry. Report only.

Scans scripts/, common/, kernel/, uboot-port/, rust/ (.py .c .h .S .rs .dts .dtsi); skips generated files
(header says generated / do not edit) and build artifacts. Match = exact register, block/region base, or inside a block/region.
Collisions exist: 0x1c000000 is also the L2X S-channel table id (kernel/us48-cmic), so hits are context-dependent.
Usage: python3 scripts/hwdb_lint.py [--all] [--by-file]   (--all also lists literals with no hwdb entry)
Log: tmp/logs/hwdb_lint.log. Exit 0 always (report only).
"""
import logging
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import hwdb  # noqa: E402
from _cli import help_guard  # noqa: E402

ROOT = hwdb.repo_root()
DIRS = ("scripts", "common", "kernel", "uboot-port", "rust")
EXT = {".py", ".c", ".h", ".S", ".rs", ".dts", ".dtsi"}
SKIP_PARTS = {"__pycache__", "target", ".git"}
LIT = re.compile(r"\b0[xX]((?:18|19|1[bB]|1[cC]|48)[0-9a-fA-F]{2}_?[0-9a-fA-F]{4})(?:[uUlL]*)\b")
SELF = {"hwdb.py", "hwdb_gen.py", "hwdb_lint.py"}


def generated(path):
    try:
        head = path.read_text(errors="replace")[:400].lower()
    except OSError:
        return True
    return "generated" in head and ("do not edit" in head or "generated by" in head)


def files():
    for d in DIRS:
        for p in sorted((ROOT / d).rglob("*")):
            if p.is_file() and p.suffix in EXT and not (SKIP_PARTS & set(p.parts)) and p.name not in SELF \
                    and "hwdb" not in p.relative_to(ROOT).parts[:1]:
                yield p


def main(argv):
    log = ROOT / "tmp/logs/hwdb_lint.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(message)s",
                        handlers=[logging.FileHandler(log), logging.StreamHandler(sys.stdout)])
    db = hwdb.load()
    show_all = "--all" in argv
    hits, miss, per_file = 0, 0, {}
    for p in files():
        if generated(p):
            continue
        rel = p.relative_to(ROOT)
        for n, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
            for m in LIT.finditer(line):
                a = int(m.group(1).replace("_", ""), 16)
                found = db.find(a)
                if found:
                    hits += 1
                    per_file[str(rel)] = per_file.get(str(rel), 0) + 1
                    k, name, off = found[0]
                    logging.info("%s:%d 0x%08x -> %s %s%s", rel, n, a, k, name, (" +0x%x" % off) if off else "")
                else:
                    miss += 1
                    if show_all:
                        logging.info("%s:%d 0x%08x -> (no hwdb entry)", rel, n, a)
    if "--by-file" in argv:
        for f, c in sorted(per_file.items(), key=lambda x: -x[1]):
            logging.info("%5d %s", c, f)
    logging.info("hwdb_lint: %d literals match hwdb, %d do not, %d files with hits", hits, miss, len(per_file))
    return 0


if __name__ == "__main__":
    help_guard(__doc__)
    sys.exit(main(sys.argv))

#!/usr/bin/env python3
"""List hard-coded MMIO literals (0x18/19/1b/1c/48 xxxxxx) that match an hwdb entry. Report only.

Scans scripts/, common/, kernel/, uboot-port/, rust/ (.py .c .h .S .rs .dts .dtsi); skips generated files
(header says generated / do not edit) and build artifacts. Match = exact register, block/region base, or inside a block/region.
Collisions exist: 0x1c000000 is also the L2X S-channel table id (kernel/us48-cmic), so hits are context-dependent.
Usage: python3 scripts/hwdb_lint.py [--all] [--by-file]   (--all also lists literals with no hwdb entry)
Base check (always runs): literal CMIC/IPROC bases (hwdb cmic0, cmic1, cmic1_uboot, iproc_axi) in scripts/ and kernel/
outside scripts/hwdb_lint_allow.txt (`path<TAB>0xBASE<TAB>reason`, one row per file+base) fail with exit 1; stale rows are reported.
Port check (also fails, same allowlist, rows `path<TAB>token<TAB>reason`): quoted loop-cable netdevs (ge8 ge17 ge32 ge41), sw1 peers
(lan3 lan6 lan7), the management netdev and front MACs 02:75:73:34:38:01..34 in scripts/*.py; use hwdb.lite() instead.
Log: tmp/logs/hwdb_lint.log. Exit 0 for the report, 1 on a new base or port literal.
"""
import logging
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import hwdb  # noqa: E402
from _cli import help_guard  # noqa: E402

ROOT = hwdb.repo_root()
DIRS = ("scripts", "common", "kernel", "uboot-port", "rust")
EXT = {".py", ".c", ".h", ".S", ".rs", ".dts", ".dtsi"}
SKIP_PARTS = {"__pycache__", "target", ".git"}
LIT = re.compile(r"\b0[xX]((?:18|19|1[bB]|1[cC]|48)[0-9a-fA-F]{2}_?[0-9a-fA-F]{4})(?:[uUlL]*)\b")
SELF = {"hwdb.py", "hwdb_gen.py", "hwdb_lint.py"}


def generated(path):
    try:
        head = path.read_text(errors="replace")[:400].lower()
    except OSError:
        return True
    return "generated" in head and ("do not edit" in head or "generated by" in head)


def files():
    for d in DIRS:
        for p in sorted((ROOT / d).rglob("*")):
            if p.is_file() and p.suffix in EXT and not (SKIP_PARTS & set(p.parts)) and p.name not in SELF \
                    and "hwdb" not in p.relative_to(ROOT).parts[:1]:
                yield p


def tracked_files():
    """Paths tracked by git (relative to ROOT), or None outside a git checkout."""
    import subprocess
    r = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z"], capture_output=True, text=True, timeout=30)
    return set(r.stdout.split("\0")) if r.returncode == 0 else None


BASE_DIRS = ("scripts", "kernel")
BASE_NAMES = ("cmic0", "cmic1", "cmic1_uboot", "iproc_axi")
ALLOW = ROOT / "scripts/hwdb_lint_allow.txt"


def base_check(db):
    """Literal CMIC/IPROC base addresses outside the allowlist. Returns the number of violations."""
    bases = {db.addr(n): n for n in BASE_NAMES}
    pat = re.compile(r"\b0[xX](%s)\b" % "|".join("0*%x" % b for b in bases), re.I)
    allow = {}
    for ln in ALLOW.read_text().splitlines() if ALLOW.exists() else []:
        if ln.strip() and not ln.startswith("#"):
            f = ln.split("\t")
            if f[1].startswith("0x"):
                allow[(f[0], int(f[1], 16))] = False
    bad = 0
    tracked = tracked_files()  # gitignored build copies (kernel/us48-cmic/bcm_cmic.h etc.) are not ours to lint
    for d in BASE_DIRS:
        for p in sorted((ROOT / d).rglob("*")):
            if not (p.is_file() and p.suffix in EXT and not (SKIP_PARTS & set(p.parts))) or generated(p):
                continue
            if tracked is not None and str(p.relative_to(ROOT)) not in tracked:
                continue
            rel = str(p.relative_to(ROOT))
            for n, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
                for m in pat.finditer(line):
                    a = int(m.group(1), 16)
                    if (rel, a) in allow:
                        allow[(rel, a)] = True
                    else:
                        bad += 1
                        logging.info("BASE %s:%d 0x%08x is hwdb %s: use hwdb.cmic_base()/addr() or HW_%s_BASE, or add to %s",
                                     rel, n, a, bases[a], bases[a].upper(), ALLOW.name)
    for (f, a), used in allow.items():
        if not used:
            logging.info("STALE allowlist row %s 0x%08x (no such literal)", f, a)
    logging.info("hwdb_lint base check: %d new literal(s)", bad)
    return bad


def port_check(db):
    """Literal loop-cable netdevs, sw1 peers, management netdev and front MACs in scripts/*.py outside the allowlist."""
    toks = {db.netdev(f) for g in db.loop_pairs() for f in g[1:]} | set(db.sw1_cages().values())
    toks.add(db.mgmt_netdev())
    pat = re.compile(r"[\"'](%s)[\"']|(02:75:73:34:38:(?:0[1-9a-f]|[12][0-9a-f]|3[0-4]))\b" % "|".join(sorted(toks)), re.I)
    allow = {}
    for ln in ALLOW.read_text().splitlines() if ALLOW.exists() else []:
        f = ln.split("\t")
        if len(f) > 1 and not ln.startswith("#") and not f[1].startswith("0x"):
            allow[(f[0], f[1])] = False
    tracked = tracked_files()
    bad = 0
    for p in sorted((ROOT / "scripts").glob("*.py")):
        rel = str(p.relative_to(ROOT))
        if p.name in SELF or (tracked is not None and rel not in tracked):
            continue
        for n, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
            for m in pat.finditer(line):
                tok = m.group(1) or "mac"
                if (rel, tok) in allow:
                    allow[(rel, tok)] = True
                else:
                    bad += 1
                    logging.info("PORT %s:%d %s is in hwdb/board/ports.toml: use hwdb.lite() (loop_pairs, sw1_peer, mgmt_netdev, mac) or add to %s",
                                 rel, n, m.group(0), ALLOW.name)
    for (f, t), used in allow.items():
        if not used:
            logging.info("STALE allowlist row %s %s (no such literal)", f, t)
    logging.info("hwdb_lint port check: %d new literal(s)", bad)
    return bad


def main(argv):
    log = ROOT / "tmp/logs/hwdb_lint.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(message)s",
                        handlers=[logging.FileHandler(log), logging.StreamHandler(sys.stdout)])
    db = hwdb.load()
    show_all = "--all" in argv
    hits, miss, per_file = 0, 0, {}
    for p in files():
        if generated(p):
            continue
        rel = p.relative_to(ROOT)
        for n, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
            for m in LIT.finditer(line):
                a = int(m.group(1).replace("_", ""), 16)
                found = db.find(a)
                if found:
                    hits += 1
                    per_file[str(rel)] = per_file.get(str(rel), 0) + 1
                    k, name, off = found[0]
                    logging.info("%s:%d 0x%08x -> %s %s%s", rel, n, a, k, name, (" +0x%x" % off) if off else "")
                else:
                    miss += 1
                    if show_all:
                        logging.info("%s:%d 0x%08x -> (no hwdb entry)", rel, n, a)
    if "--by-file" in argv:
        for f, c in sorted(per_file.items(), key=lambda x: -x[1]):
            logging.info("%5d %s", c, f)
    logging.info("hwdb_lint: %d literals match hwdb, %d do not, %d files with hits", hits, miss, len(per_file))
    return 1 if (base_check(db) + port_check(db)) else 0


if __name__ == "__main__":
    help_guard(__doc__)
    sys.exit(main(sys.argv))

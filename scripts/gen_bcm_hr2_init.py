#!/usr/bin/env python3
"""gen_bcm_hr2_init — filtered stock unit-0 S-channel write trace -> common/bcm-cmic/bcm_cmic_hr2_init_data.h.

Usage: scripts/gen_bcm_hr2_init.py [--report]
- Input: tmp/schan_stock_init.log (raw S-channel trace, unit u0) + tmp/schan_stock_writes.txt (register names per seq).
- Name filter applies to the TOP block (16) only. Keeps, in trace order, the chip-global init plus the CPU port (0) and front 1 (logical 2, GPORT0 lane 7) entries.
  Drops XLPORT/HiGig (blk 5/6), GPORT1/2 (3/4), SER (19), parity/ECC/interrupt/PLL(TS,BS)/LED/EEE/debug regs,
  big all-zero table clears, other ports' per-port registers, EPC_LINK_BMAP_64 (the driver sets its own bits).
- Output entry: {cat<<24 | op<<16 | blk<<8 | words, addr, data...}; cat 0xff = delay of low-16-bit ms. cat bits: 1 TOP,
  2 global, 4 CPU/front-1 per-port, 8 non-zero tables, 16 other ports' regs, 64 parity/ECC/interrupt regs (runtime mask).
- Log: tmp/logs/gen_bcm_hr2_init.log
"""
import collections
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import schan_summarize as ss  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "tmp/schan_stock_init.log"
NAMED = ROOT / "tmp/schan_stock_writes.txt"
OUT = ROOT / "common/bcm-cmic/bcm_cmic_hr2_init_data.h"
OUT_X = ROOT / "common/bcm-cmic/bcm_cmic_hr2_init_x.h"
LOG = ROOT / "tmp/logs/gen_bcm_hr2_init.log"
SEQ_LO, SEQ_HI = 1108, 10**9    # whole trace: stock reconfigures MMU/ports after seq 59000 (second pass at ~124000)
MEM_SEQ_HI = 59000               # tables after this are runtime VLAN/L2 churn
SKIP_NAME = re.compile(r"PARITY|ECC|INTR|BISR|^TOP_TS_PLL|^TOP_BS_PLL|BROAD_SYNC|LEDUP|EEE|DEBUG|MEMFAIL|TIMESYNC|"
                       r"^SER_|CMIC_|IPMCGROUP|OTPC|GBOD|EPC_LINK_BMAP|XLPORT|XLMAC|MAXBUCKETCONFIG|"
                       r"^IARB_PKT_ECC|E2EFC|^TOP_HW_TAP|I2CM|^TOP_PVTMON|^TOP_XG_PLL|FLUSH_CONTROL")
KEEP_PORTS = {0, 2}              # CPU, front 1 logical
LANE = 7                         # GPORT0 lane of front 1
# dropped writes -> OUT_X, last value per (op, blk, addr); entry: group << 24 | op << 16 | blk << 8 | words, addr, data...
# run-time mask bit = 1 << group (env us48_init_xmask, command hr2x)
XGROUPS = ["cpu_cos_map", "egr_pri_cng_map", "source_trunk_map", "ipipe_mem", "epipe_mem", "ser", "gport12", "xlport", "other"]
CAT_TOP, CAT_GLOBAL, CAT_PORT, CAT_MEM, CAT_OTHERPORT, CAT_ECC = 1, 2, 4, 8, 16, 64


def xgroup(op, blk, addr, mems) -> int:
    if blk in (3, 4):
        return XGROUPS.index("gport12")
    if blk in (5, 6):
        return XGROUPS.index("xlport")
    if blk == 19:
        return XGROUPS.index("ser")
    if op == 0x09 and blk in (10, 11):
        nm = next((m[2] for m in reversed(mems) if m[0] <= addr <= m[0] + m[1] and blk in m[3]), "")
        for g, key in (("cpu_cos_map", "CPU_COS_MAP"), ("egr_pri_cng_map", "EGR_PRI_CNG_MAP"),
                       ("source_trunk_map", "SOURCE_TRUNK_MAP_TABLE")):
            if nm == key:
                return XGROUPS.index(g)
        return XGROUPS.index("ipipe_mem" if blk == 10 else "epipe_mem")
    return XGROUPS.index("other")


def write_x(xdrop, mems) -> None:
    last = {}
    for seq, op, blk, addr, data in xdrop:
        last.pop((op, blk, addr), None)
        last[(op, blk, addr)] = (seq, data)
    lines = ["/* Generated by scripts/gen_bcm_hr2_init.py: stock writes the main replay drops (last value per address). */",
             "/* entry: group << 24 | op << 16 | blk << 8 | words, addr, data...; groups: " + ", ".join(f"{i} {g}" for i, g in enumerate(XGROUPS)) + " */"]
    cnt = collections.Counter()
    words = 0
    for (op, blk, addr), (seq, data) in sorted(last.items(), key=lambda kv: kv[1][0]):
        g = xgroup(op, blk, addr, mems)
        cnt[XGROUPS[g]] += 1
        lines.append(f"\t0x{g:02x}{op:02x}{blk:02x}{len(data):02x}, 0x{addr:08x}, " + ", ".join(f"0x{d:08x}" for d in data) + ",")
        words += 2 + len(data)
    OUT_X.write_text("\n".join(lines) + f"\n/* {words} words */\n")
    print(f"x: {len(last)} entries, {words} words: {dict(cnt)}")


def main() -> int:
    names = {}
    for ln in NAMED.read_text().splitlines():
        f = ln.split()
        if len(f) > 6 and f[1] == "u0":
            names[(int(f[0]), int(f[4], 16) & 0xffffff)] = re.sub(r"\[.*", "", f[6])
    ops = []
    for ln in RAW.read_text().splitlines():
        f = ln.split()
        if len(f) < 5 or f[2] != "u0":
            continue
        seq, hdr, addr = int(f[0]), int(f[3], 16), int(f[4], 16)
        op, blk = hdr >> 26, (hdr >> 20) & 0x3f
        data = [int(x, 16) for x in f[5:5 + ((hdr >> 7) & 0x7f) // 4]]
        if op not in (0x0d, 0x09) or not data or not SEQ_LO <= seq <= SEQ_HI:
            continue
        ops.append((seq, op, blk, addr, data))
    # per-port register bases: >= 20 distinct low bytes under the same (blk, addr >> 8)
    lows = collections.defaultdict(set)
    for _s, op, blk, addr, _d in ops:
        if op == 0x0d:
            lows[(blk, addr >> 8)].add(addr & 0xff)
    memcount = collections.Counter((blk, addr >> 12) for _s, op, blk, addr, _d in ops if op == 0x09)
    keep = []
    xdrop = []
    mems, _regs = ss.load_names()
    why = collections.Counter()
    pat_ecc = re.compile(r"PARITY|ECC|INTR|BISR|MEMFAIL|SER_|BIST|DEBUG")
    for seq, op, blk, addr, data in ops:
        name = names.get((seq, addr), "")
        if blk in (3, 4, 5, 6, 19):
            why["blk 3/4/5/6/19"] += 1
            xdrop.append((seq, op, blk, addr, data))
            continue
        if op == 0x09 and seq > MEM_SEQ_HI:
            why["late table"] += 1
            xdrop.append((seq, op, blk, addr, data))
            continue
        if blk == 10 and addr == 0x46002700:  # EPC_LINK_BMAP_64: the driver sets its own bits
            why["epc link"] += 1
            continue
        if blk == 16:
            if SKIP_NAME.search(name):
                why["top pll/pvtmon"] += 1
                continue
            cat = CAT_TOP
        elif op == 0x09:
            if not any(data) and memcount[(blk, addr >> 12)] > 100 and blk != 12:
                why["zero table (IPIPE/EPIPE: pipe reset clears)"] += 1
                xdrop.append((seq, op, blk, addr, data))
                continue
            cat = CAT_MEM
        elif blk == 2:
            cat = CAT_PORT if (addr >= 0x2000000 or (addr & 0xff) == LANE) else CAT_OTHERPORT
        else:
            per_port = len(lows[(blk, addr >> 8)]) >= 20
            if per_port and (addr & 0xff) not in KEEP_PORTS:
                cat = CAT_OTHERPORT
            elif pat_ecc.search(name):
                cat = CAT_ECC
            else:
                cat = CAT_PORT if per_port else CAT_GLOBAL
        keep.append((seq, op, blk, addr, data, name, cat))
    lines = [f"/* Generated by scripts/gen_bcm_hr2_init.py from the stock unit-0 S-channel trace: {len(keep)} ops. */",
             "/* entry: cat << 24 | op << 16 | blk << 8 | words, addr, data...; cat 0xff = delay (ms in low 16 bits) */"]
    words = 0
    prev = None
    for seq, op, blk, addr, data, name, cat in keep:
        if prev is not None and seq - prev >= 8:
            lines.append("\t0xff00000a, /* delay 10 ms */")
            words += 1
        prev = seq
        lines.append(f"\t0x{cat:02x}{op:02x}{blk:02x}{len(data):02x}, 0x{addr:08x}, " + ", ".join(f"0x{d:08x}" for d in data) +
                     f", /* {seq} {name} */")
        words += 2 + len(data)
    write_x(xdrop, mems)
    OUT.write_text("\n".join(lines) + f"\n/* {words} words */\n")
    why.update({f"cat {k:#x}": sum(1 for x in keep if x[6] == k) for k in (CAT_TOP, CAT_GLOBAL, CAT_PORT, CAT_MEM, CAT_OTHERPORT, CAT_ECC)})
    msg = f"kept {len(keep)} of {len(ops)} ops, {words} words; dropped {dict(why)}"
    LOG.parent.mkdir(parents=True, exist_ok=True)
    LOG.write_text(msg + "\n")
    print(msg)
    return 0


if __name__ == "__main__":
    sys.exit(main())

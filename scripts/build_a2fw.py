#!/usr/bin/env python3
"""Build a2fw/ -> tmp/a2fw/us48-a2.elf (self-test) and us48-a2-boot.elf (Linux boot stub) for the us48_a2 remoteproc driver.

Toolchain = the one build_a2_stub.py uses (private/tools/arm-linux-musleabi-cross). Code links at hwdb a2_stub, resource table + trace at a2_shared; the carveout in the DT (mainline/0010) must match hwdb. Log: tmp/logs/build_a2fw.log.
"""
import logging
import pathlib
import re
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import hwdb  # noqa: E402

ROOT = hwdb.repo_root()
T = ROOT / "private/tools/arm-linux-musleabi-cross/bin/arm-linux-musleabi-"
SRC = ROOT / "a2fw"
OUT = ROOT / "tmp/a2fw"
LOG = ROOT / "tmp/logs/build_a2fw.log"
CFLAGS = ["-mcpu=cortex-a9", "-marm", "-mfloat-abi=soft", "-O2", "-Wall", "-Wextra", "-Werror", "-ffreestanding",
          "-fno-pic", "-nostdlib", "-fno-builtin", "-I", str(ROOT / "hwdb/gen")]
# A compile or link is milliseconds on this host; 30 s = expiry means a hung tool, logged with the command.
STEP_TIMEOUT_S = 30
BIG = ["-DBIG_LINES=2048"]  # iftest_asm.S: 64 KiB of straight-line code, 2x the 32 KiB L1 I


def run(cmd):
    logging.info("$ %s", " ".join(map(str, cmd)))
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=STEP_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        logging.error("timeout after %d s", STEP_TIMEOUT_S)
        sys.exit(1)
    for line in (r.stdout + r.stderr).splitlines():
        logging.info(line)
    if r.returncode:
        logging.error("FAILED rc=%d", r.returncode)
        sys.exit(r.returncode)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    LOG.parent.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(message)s",
                        handlers=[logging.FileHandler(LOG, mode="w"), logging.StreamHandler(sys.stdout)])
    db = hwdb.load(sdk=False)
    reg = db.region("a2_stub")
    sh = db.region("a2_shared")  # resource table + trace: the first MiB becomes kernel RAM in payload mode
    hdr = (SRC / "us48_a2_boot.h").read_text()
    bootargs_off = int(re.search(r"US48_A2_BOOT_ARGS_OFF\s+(0x[0-9a-fA-F]+)", hdr).group(1), 16)  # single source
    ld = OUT / "a2fw.ld"
    ld.write_text(f"""/* generated by scripts/build_a2fw.py from hwdb region a2_carveout */
ENTRY(_start)
SECTIONS {{
  . = 0x{reg.base:08x};
  .text : {{ *(.text.start) *(.text*) *(.rodata*) }}
  .bootargs 0x{reg.base + bootargs_off:08x} : {{ KEEP(*(.bootargs)) }}
@ASSERT@  .data : {{ *(.data*) }}
  .bss : ALIGN(4096) {{ *(.bss*) *(COMMON) }}
  .resource_table 0x{sh.base:08x} : {{ KEEP(*(.resource_table)) }}
  .trace 0x{sh.base + 0x1000:08x} : {{ *(.trace) }}
  __stack_top = 0x{reg.base + reg.size - 16:08x};
  /DISCARD/ : {{ *(.ARM.*) *(.comment) *(.note*) }}
}}
""")
    # (name, sources, extra cflags); bustest = PCIe harness firmware (#80), -nommu = fallback without the MMU setup
    for name, srcs, extra in (("us48-a2", ("start.S", "main.c"), []), ("us48-a2-boot", ("boot.S", "bootrsc.c"), []),
                              ("us48-a2-bustest", ("start.S", "bustest.c"), []),
                              ("us48-a2-bustest-nommu", ("start.S", "bustest.c"), ["-DNO_MMU"]),
                              ("us48-a2-rawtest", ("start.S", "rawtest.c"), []),  # read-after-write ordering (#79)
                              ("us48-a2-rawtest-noic", ("start.S", "rawtest.c"), ["-DNO_ICACHE"]),  # cache probes (#79)
                              ("us48-a2-rawtest-nodc", ("start.S", "rawtest.c"), ["-DNO_DCACHE"]),
                              # rawtest bisect (#79): one test group per ELF, setup only, PT read-back
                              ("us48-a2-rawtest-A", ("start.S", "rawtest.c"), ["-DTESTMASK=0x0fU"]),
                              ("us48-a2-rawtest-B", ("start.S", "rawtest.c"), ["-DTESTMASK=0xf0U"]),
                              ("us48-a2-rawtest-C", ("start.S", "rawtest.c"), ["-DTESTMASK=0x100U"]),
                              ("us48-a2-rawtest-D", ("start.S", "rawtest.c"), ["-DTESTMASK=0x200U"]),
                              ("us48-a2-rawtest-A0", ("start.S", "rawtest.c"), ["-DTESTMASK=0x01U"]),
                              ("us48-a2-rawtest-A1", ("start.S", "rawtest.c"), ["-DTESTMASK=0x02U"]),
                              ("us48-a2-rawtest-A2", ("start.S", "rawtest.c"), ["-DTESTMASK=0x04U"]),
                              ("us48-a2-rawtest-A3", ("start.S", "rawtest.c"), ["-DTESTMASK=0x08U"]),
                              ("us48-a2-rawtest-A1-ptsram", ("start.S", "rawtest.c"), ["-DTESTMASK=0x02U", "-DPT_SRAM"]),
                              ("us48-a2-rawtest-ptsram", ("start.S", "rawtest.c"), ["-DPT_SRAM"]),
                              ("us48-a2-rawtest-wbonly-alias", ("start.S", "rawtest.c"), ["-DTESTMASK=0x311U"]),
                              ("us48-a2-rawtest-wbonly-noalias", ("start.S", "rawtest.c"), ["-DTESTMASK=0x311U", "-DNO_ALIAS"]),
                              ("us48-a2-rawtest-setup", ("start.S", "rawtest.c"), ["-DTESTMASK=0"]),
                              ("us48-a2-rawtest-rb", ("start.S", "rawtest.c"), ["-DPT_RB"]),
                              # I-fetch / D-fill probes (#79): ifa code in SRAM, ifb data in SRAM, ifd both over PCIe
                              ("us48-a2-ifa", ("start.S", "iftest.c", "iftest_asm.S"), ["-DIF_A", *BIG, "-DWRAP_DATA=0"]),
                              ("us48-a2-ifb", ("start.S", "iftest.c", "iftest_asm.S"), ["-DIF_B", *BIG, "-DWRAP_DATA=1"]),
                              ("us48-a2-ifd", ("start.S", "iftest.c", "iftest_asm.S"), ["-DIF_D", *BIG, "-DWRAP_DATA=0"]),
                              # (c) Diagnostic bit 22 (UAN0009 845369) and NIC-301 PCIe0 slave issuing = 1, on the failing rawtest and ifd
                              ("us48-a2-rawtest-diag22", ("start.S", "rawtest.c"), ["-DDIAG_SET=0x400000"]),
                              ("us48-a2-rawtest-nic", ("start.S", "rawtest.c"), ["-DNIC_ISS=3"]),
                              ("us48-a2-rawtest-diag22-nic", ("start.S", "rawtest.c"), ["-DDIAG_SET=0x400000", "-DNIC_ISS=3"]),
                              ("us48-a2-ifd-diag22-nic", ("start.S", "iftest.c", "iftest_asm.S"),
                               ["-DIF_D", *BIG, "-DWRAP_DATA=0", "-DDIAG_SET=0x400000", "-DNIC_ISS=3"])):
        objs = []
        for src in srcs:
            obj = OUT / f"{name}-{src}.o"
            run([f"{T}gcc", *CFLAGS, *extra, "-c", "-o", obj, SRC / src])
            objs.append(obj)
        elf = OUT / f"{name}.elf"
        # only the boot stub has boot args (the others link bigger code over that offset)
        ld_name = OUT / f"{name}.ld"
        guard = f'  ASSERT(SIZEOF(.text) <= 0x{bootargs_off:x}, ".text runs into the boot args")\n' if name == "us48-a2-boot" else ""
        ld_name.write_text(ld.read_text().replace("@ASSERT@", guard))
        run([f"{T}ld", "-T", ld_name, "-o", elf, *objs])
        run([f"{T}readelf", "-lS", elf])
        logging.info("built %s (%d B), link base 0x%08x", elf.relative_to(ROOT), elf.stat().st_size, reg.base)


if __name__ == "__main__":
    main()

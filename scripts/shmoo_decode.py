#!/usr/bin/env python3
"""shmoo_decode — decode the stored DDR shmoo blob (mtd2, flash 0xd0000) offline (#55).

  shmoo_decode.py [full-flash.bin]   default: newest private/backups/*/full-flash.bin

Format = Broadcom HR2 U-Boot ddr_restore.c (D-Link DGS-1210 B1 GPL): struct shmoo_sig_t
{ "SHMO", dev_id:16, sku_id:16, ddr_type:2, ddr_clock:12, rsvd:18 }, checksum, pairs, {reg, val} x pairs.
Checksum = u32 sum of every reg and val word. Names from regdb/hr2_regs.tsv.
Output: tmp/ddr/shmoo_decoded.md; log tmp/logs/shmoo_decode.log.
"""
from __future__ import annotations

import struct
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dev import REPO  # noqa: E402  (3-tier repo root)

LOGF = REPO / "tmp/logs/shmoo_decode.log"
OUT = REPO / "tmp/ddr/shmoo_decoded.md"
SHMOO_OFF = 0xD0000


def log(msg: str) -> None:
    line = f"{time.strftime('%Y-%m-%dT%H:%M:%S%z')} {msg}"
    print(line, flush=True)
    LOGF.parent.mkdir(parents=True, exist_ok=True)
    with LOGF.open("a") as f:
        f.write(line + "\n")


def regdb() -> dict[int, tuple[str, str]]:
    names: dict[int, tuple[str, str]] = {}
    for ln in (REPO / "regdb/hr2_regs.tsv").read_text().splitlines()[1:]:
        c = ln.split("\t")
        if len(c) > 16 and c[7].startswith("0x18010"):
            names[int(c[7], 16)] = (c[1], c[16])
    return names


def main() -> int:
    if len(sys.argv) > 1:
        img = Path(sys.argv[1])
    else:
        cands = sorted((REPO / "private/backups").glob("*/full-flash.bin"))
        if not cands:
            log("no full-flash.bin under private/backups")
            return 1
        img = cands[-1]
    data = img.read_bytes()[SHMOO_OFF:SHMOO_OFF + 0x10000]
    magic, w1, w2, csum, pairs = struct.unpack_from("<4sIIII", data, 0)
    if magic != b"SHMO":
        log(f"{img}: no SHMO magic at {SHMOO_OFF:#x} ({magic!r})")
        return 1
    dev_id, sku_id = w1 & 0xFFFF, w1 >> 16
    ddr_type, ddr_clk = w2 & 3, (w2 >> 2) & 0xFFF
    words = struct.unpack_from(f"<{pairs * 2}I", data, 0x14)
    calc = sum(words) & 0xFFFFFFFF
    names = regdb()
    hdr = (f"image {img}\ndev_id {dev_id:#06x} ({dev_id}) sku_id {sku_id:#06x} ddr_type {ddr_type} "
           f"({'DDR3' if ddr_type else 'DDR2'}) ddr_clock {ddr_clk} MHz\n"
           f"checksum stored {csum:#010x} calc {calc:#010x} {'OK' if calc == csum else 'MISMATCH'}; pairs {pairs}; "
           f"used bytes {0x14 + pairs * 8:#x}")
    log(hdr)
    rows = ["| # | reg | value | name | fields |", "|---|---|---|---|---|"]
    for i in range(pairs):
        reg, val = words[2 * i], words[2 * i + 1]
        name, fields = names.get(reg, ("?", ""))
        dec = []
        for f in filter(None, fields.split(",")):
            fn, sh, wd = f.rsplit(":", 2)
            if fn.startswith("RESERVED"):
                continue
            v = (val >> int(sh)) & ((1 << int(wd)) - 1)
            if v:
                dec.append(f"{fn}={v}")
        rows.append(f"| {i} | `{reg:#010x}` | `{val:#010x}` | {name} | {' '.join(dec)} |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("# Shmoo blob decode (generated by scripts/shmoo_decode.py)\n\n```\n" + hdr + "\n```\n\n"
                   + "\n".join(rows) + "\n")
    log(f"wrote {OUT}")
    return 0 if calc == csum else 1


if __name__ == "__main__":
    sys.exit(main())

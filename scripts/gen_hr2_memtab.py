#!/usr/bin/env python3
"""gen_hr2_memtab — regdb/hr2_mems.tsv -> common/bcm-cmic/bcm_cmic_hr2_memtab.h (memory list for `hr2mem`, #46 option A).

Usage: scripts/gen_hr2_memtab.py
- One row per memory on IPIPE (blk 10), EPIPE (11) and MMU (12): name, S-channel block, base, entries, words/entry.
- Skipped: MMU_CBPDATA*/CBPPKTHEADER0/1 (packet buffer, 16 words x 12288 each), SER_* (blk 19 self-test), XLPORT_* (not clocked cold).
- Log: tmp/logs/gen_hr2_memtab.log
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "regdb/hr2_mems.tsv"
OUT = ROOT / "common/bcm-cmic/bcm_cmic_hr2_memtab.h"
LOG = ROOT / "tmp/logs/gen_hr2_memtab.log"
SKIP = re.compile(r"^(MMU_CBPDATA|MMU_CBPPKTHEADER[01]$|SER_|XLPORT)")
BLKS = {"IPIPE": 10, "EPIPE": 11, "MMU": 12}


def main() -> None:
    rows, words = [], 0
    for r in csv.DictReader(SRC.open(), delimiter="\t"):
        lab = r["block_labels"].split(",")[0]
        if SKIP.match(r["name"]) or lab not in BLKS or int(r["index_min"]) != 0:
            continue
        n, w = int(r["index_max"]) + 1, (int(r["nbits"]) + 31) // 32
        rows.append((r["name"], BLKS[lab], int(r["base"], 16), n, w))
        words += n * w
    rows.sort(key=lambda x: (x[1], x[2]))
    out = ["/* Generated by scripts/gen_hr2_memtab.py from regdb/hr2_mems.tsv. Do not edit. */",
           "/* { name, S-channel block, base address (entry address = base + index), entries, words per entry } */"]
    out += [f'\t{{ "{n}", {b}, 0x{base:08x}, {c}, {w} }},' for n, b, base, c, w in rows]
    OUT.write_text("\n".join(out) + "\n")
    LOG.parent.mkdir(parents=True, exist_ok=True)
    LOG.write_text(f"{len(rows)} memories, {sum(r[3] for r in rows)} entries, {words} words -> {OUT}\n")
    print(LOG.read_text(), end="")


if __name__ == "__main__":
    main()
